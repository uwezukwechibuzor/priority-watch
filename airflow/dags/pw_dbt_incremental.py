"""pw_dbt_incremental — run dbt incremental models every 10 minutes.

Uses Astronomer Cosmos to render dbt models as native Airflow tasks.
Runs in three sequential groups: staging → intermediate → marts.
Tests are skipped here — they run in pw_dbt_nightly to avoid scanning
multi-million-row tables (stg_logs, stg_transactions) every 10 minutes.
"""
from __future__ import annotations

from datetime import datetime
from pathlib import Path

from airflow.decorators import dag
from cosmos import DbtTaskGroup, ExecutionConfig, ProfileConfig, ProjectConfig, RenderConfig
from cosmos.constants import ExecutionMode, LoadMode, TestBehavior

from _shared import (
    DBT_EXECUTABLE,
    DBT_MANIFEST_PATH,
    DBT_PROFILES_DIR,
    DBT_PROJECT_DIR,
    DBT_TARGET,
    DEFAULT_ARGS,
)

# Use pre-built manifest so Cosmos never runs `dbt ls` at DAG-parse time.
# The manifest is regenerated by pw_dbt_nightly's docs-generate step.
_project_config = ProjectConfig(
    dbt_project_path=Path(DBT_PROJECT_DIR),
    manifest_path=Path(DBT_MANIFEST_PATH),
)

_profile_config = ProfileConfig(
    profile_name="priority_watch",
    target_name=DBT_TARGET,
    profiles_yml_filepath=Path(DBT_PROFILES_DIR) / "profiles.yml",
)

_execution_config = ExecutionConfig(
    execution_mode=ExecutionMode.LOCAL,
    dbt_executable_path=DBT_EXECUTABLE,
)


def _render(tag: str) -> RenderConfig:
    return RenderConfig(
        select=[f"tag:{tag}"],
        test_behavior=TestBehavior.NONE,
        load_method=LoadMode.DBT_MANIFEST,
    )


@dag(
    dag_id="pw_dbt_incremental",
    schedule="*/10 * * * *",
    start_date=datetime(2026, 1, 1),
    catchup=False,
    tags=["pga", "dbt", "incremental"],
    default_args=DEFAULT_ARGS,
    max_active_runs=1,
    is_paused_upon_creation=False,
    doc_md=__doc__,
)
def pw_dbt_incremental() -> None:
    staging = DbtTaskGroup(
        group_id="staging",
        project_config=_project_config,
        profile_config=_profile_config,
        execution_config=_execution_config,
        render_config=_render("staging"),
    )

    intermediate = DbtTaskGroup(
        group_id="intermediate",
        project_config=_project_config,
        profile_config=_profile_config,
        execution_config=_execution_config,
        render_config=_render("intermediate"),
    )

    marts = DbtTaskGroup(
        group_id="marts",
        project_config=_project_config,
        profile_config=_profile_config,
        execution_config=_execution_config,
        render_config=_render("marts"),
    )

    staging >> intermediate >> marts


pw_dbt_incremental()
